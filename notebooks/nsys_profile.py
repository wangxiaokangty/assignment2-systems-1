@app.cell
def _(Path, pd):
    _summaries = []
    for _path in sorted(Path("results").glob("nsys_profile_*_cuda_gpu_kern_sum.csv")):
        _frame = pd.read_csv(_path)
        if _frame.empty:
            continue
        _matmul = _frame["Name"].str.contains("gemm|gemv|xmma", case=False)
        _summaries.append({"profile": _path.stem.removesuffix("_cuda_gpu_kern_sum"),
                           "top_kernel": _frame.iloc[0]["Name"], "calls": _frame.iloc[0]["Instances"],
                           "top_kernel_ms": _frame.iloc[0]["Total Time (ns)"]/1e6,
                           "matmul_fraction_percent": 100*_frame.loc[_matmul,"Total Time (ns)"].sum()/_frame["Total Time (ns)"].sum()})
    pd.DataFrame(_summaries)
    return


